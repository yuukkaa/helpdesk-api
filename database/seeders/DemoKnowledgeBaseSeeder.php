<?php

namespace Database\Seeders;

use App\Models\Category;
use App\Models\KnowledgeBaseArticle;
use App\Models\User;
use Illuminate\Database\Seeder;

/** Статьи базы знаний с осмысленным текстом для демонстрации RAG. */
class DemoKnowledgeBaseSeeder extends Seeder
{
    public function run(): void
    {
        // Категории для демонстрации ИИ: создаются, если их ещё нет
        foreach (['Доступ и пароли', 'Оплата и тарифы', 'Ошибки приложения', 'Оборудование', 'Сеть и VPN', 'Почта', 'Отчёты', 'Прочее'] as $name) {
            Category::firstOrCreate(['name' => $name]);
        }

        $author = User::where('role', 'support')->first() ?? User::first();

        $articles = [
            ['Как сбросить пароль', 'Откройте страницу входа и нажмите «Забыли пароль». Введите адрес электронной почты, на него придёт ссылка для смены пароля. Ссылка действует 60 минут. Если письмо не пришло, проверьте папку «Спам». После пяти неверных попыток входа учётная запись блокируется на 15 минут.'],
            ['Что делать при двойном списании', 'Двойное списание обычно возникает при повторной оплате из-за сбоя платёжного шлюза. Приложите к обращению выписку из банка или чек. Мы проверим платёж и вернём лишнюю сумму на карту в течение 5 рабочих дней.'],
            ['Настройка VPN-клиента и токена', 'Установите VPN-клиент, импортируйте профиль из личного кабинета и привяжите токен. Если токен не генерирует код, проверьте заряд батареи и синхронизацию времени на устройстве. При повторной ошибке закажите замену токена.'],
            ['Типовые причины ошибки 500', 'Ошибка 500 означает сбой на стороне сервера. Попробуйте обновить страницу через несколько минут и очистить кэш браузера. Если ошибка повторяется при загрузке отчёта, приложите к обращению файл журнала и время возникновения ошибки.'],
            ['Как изменить адрес электронной почты', 'Смена адреса выполняется через обращение в категории «Доступ и пароли». Укажите новый адрес и подтвердите владение старой почтой. После проверки специалист изменит адрес в течение одного рабочего дня.'],
            ['Как прикрепить файл к обращению', 'К обращению можно прикрепить до пяти файлов размером до 10 МБ. Допустимые форматы: JPG, PNG, PDF, TXT и LOG. Если файл не открывается или не загружается, проверьте его размер и формат.'],
        ];

        foreach ($articles as [$title, $content]) {
            KnowledgeBaseArticle::create([
                'user_id' => $author->id,
                'category_id' => null,
                'title' => $title,
                'content' => $content,
                'is_published' => true,
            ]);
        }
    }
}
